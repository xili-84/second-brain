#!/usr/bin/env python3
"""Generate the Second Brain icon, PWA icons, Android launcher layers and splash assets.

The mark is the wordmark reduced to its initial: a heavy Inter "S" followed by the red dot that
ends "Second Brain●". Everything is generated from one geometry so every size stays consistent.

Requirements (dev only, not part of `npm run check`): Python 3 with fonttools, brotli and
Pillow, plus `rsvg-convert` (librsvg). Run from the repository root after `npm ci`:

    python3 scripts/brand/build_brand_assets.py
"""

from __future__ import annotations

import io
import subprocess
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
FONT = ROOT / 'node_modules/@fontsource-variable/inter/files/inter-latin-wght-normal.woff2'
PUBLIC_ICONS = ROOT / 'public/icons'
PUBLIC = ROOT / 'public'
BRAND = ROOT / 'resources/brand'
RES = ROOT / 'android/app/src/main/res'

INK = '#111111'
PAPER = '#ffffff'
RED = '#c8102e'
# On the black tile the dot uses a slightly brighter red so it holds up at launcher sizes.
RED_ON_INK = '#e0203d'
DARK_BG = '#0f0f10'
DARK_INK = '#f3f3f1'
DARK_RED = '#ff5468'

WEIGHT = 800
DOT_RATIO = 0.30  # dot diameter relative to the cap height
GAP_RATIO = 0.07  # space between the S and the dot relative to the cap height


def load_glyph():
    font = TTFont(FONT)
    font = instancer.instantiateVariableFont(font, {'wght': WEIGHT})
    glyph_set = font.getGlyphSet()
    name = font.getBestCmap()[ord('S')]
    bounds = BoundsPen(glyph_set)
    glyph_set[name].draw(bounds)
    return glyph_set, name, bounds.bounds, font['OS/2'].sCapHeight


GLYPH_SET, GLYPH, (GX0, GY0, GX1, GY1), CAP = load_glyph()


def mark(cx: float, cy: float, cap: float) -> tuple[str, tuple[float, float, float]]:
    """Path data for the S and the dot (cx, cy, r), centred on (cx, cy) with the given cap height.

    Coordinates are y-down, ready for SVG and Android vector drawables.
    """
    scale = cap / (GY1 - GY0)
    s_width = (GX1 - GX0) * scale
    dot = cap * DOT_RATIO
    gap = cap * GAP_RATIO
    total = s_width + gap + dot
    left = cx - total / 2
    top = cy - cap / 2

    pen = SVGPathPen(GLYPH_SET, ntos=lambda v: f'{v:.2f}'.rstrip('0').rstrip('.'))
    # Font units are y-up; flip and move the glyph's ink box to (left, top).
    transform = (scale, 0, 0, -scale, left - GX0 * scale, top + GY1 * scale)
    GLYPH_SET[GLYPH].draw(TransformPen(pen, transform))
    r = dot / 2
    return pen.getCommands(), (left + s_width + gap + r, top + cap - r, r)


def circle_path(x: float, y: float, r: float) -> str:
    return f'M{x - r:.2f},{y:.2f}a{r:.2f},{r:.2f} 0 1,0 {2 * r:.2f},0a{r:.2f},{r:.2f} 0 1,0 {-2 * r:.2f},0Z'


def svg(size: int, cap_fraction: float, *, bg: str | None, ink: str, red: str, radius: float = 0) -> str:
    path, (x, y, r) = mark(size / 2, size / 2, size * cap_fraction)
    tile = ''
    if bg:
        tile = f'<rect width="{size}" height="{size}" rx="{radius * size:.2f}" fill="{bg}"/>'
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}" '
        f'width="{size}" height="{size}">{tile}'
        f'<path fill="{ink}" d="{path}"/><circle cx="{x:.2f}" cy="{y:.2f}" r="{r:.2f}" fill="{red}"/></svg>'
    )


def render(svg_text: str, out: Path, size: int) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    png = subprocess.run(
        ['rsvg-convert', '-w', str(size), '-h', str(size)],
        input=svg_text.encode(),
        capture_output=True,
        check=True,
    ).stdout
    image = Image.open(io.BytesIO(png))
    image.save(out, optimize=True)


def vector(viewport: int, dp: int, cap_fraction: float, ink: str, red: str) -> str:
    path, (x, y, r) = mark(viewport / 2, viewport / 2, viewport * cap_fraction)
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/brand/build_brand_assets.py. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{dp}dp"
    android:height="{dp}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}">
    <path
        android:fillColor="{ink}"
        android:pathData="{path}" />
    <path
        android:fillColor="{red}"
        android:pathData="{circle_path(x, y, r)}" />
</vector>
'''


# Cap height as a fraction of each canvas. Launchers mask adaptive icons to (at least) the
# central 66/108, maskable PWA icons to the central 80 %, and the Android 12 splash to a
# 192/288 circle, so each layout keeps the mark well inside its safe zone.
ANY_CAP = 0.44  # rounded tile used where the platform does not mask ("any")
FULL_CAP = 0.40  # full-bleed tiles the platform rounds itself (apple-touch, legacy launcher)
MASKABLE_CAP = 0.34
ADAPTIVE_CAP = 0.32
SPLASH_CAP = 0.28
FAVICON_CAP = 0.56


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def main() -> None:
    # ---- Sources and PWA ----
    write(BRAND / 'icon.svg', svg(1024, ANY_CAP, bg=INK, ink=PAPER, red=RED_ON_INK, radius=0.225))
    write(BRAND / 'icon-maskable.svg', svg(1024, MASKABLE_CAP, bg=INK, ink=PAPER, red=RED_ON_INK))
    write(BRAND / 'mark-light.svg', svg(1024, 0.5, bg=None, ink=INK, red=RED))
    write(BRAND / 'mark-dark.svg', svg(1024, 0.5, bg=None, ink=DARK_INK, red=DARK_RED))

    for size in (192, 512):
        render(svg(size, ANY_CAP, bg=INK, ink=PAPER, red=RED_ON_INK, radius=0.225), PUBLIC_ICONS / f'icon-{size}.png', size)
        render(svg(size, MASKABLE_CAP, bg=INK, ink=PAPER, red=RED_ON_INK), PUBLIC_ICONS / f'icon-maskable-{size}.png', size)
    render(svg(180, FULL_CAP, bg=INK, ink=PAPER, red=RED_ON_INK), PUBLIC_ICONS / 'apple-touch-icon.png', 180)
    favicon = svg(64, FAVICON_CAP, bg=INK, ink=PAPER, red=RED_ON_INK, radius=0.2)
    write(PUBLIC / 'favicon.svg', favicon + '\n')
    render(favicon, PUBLIC_ICONS / 'favicon-32.png', 32)
    sizes = [16, 32, 48]
    frames = []
    for size in sizes:
        tmp = BRAND / f'.favicon-{size}.png'
        render(svg(size * 4, FAVICON_CAP, bg=INK, ink=PAPER, red=RED_ON_INK, radius=0.2), tmp, size)
        frames.append(Image.open(tmp).convert('RGBA'))
        tmp.unlink()
    frames[-1].save(PUBLIC / 'favicon.ico', sizes=[(s, s) for s in sizes], append_images=frames[:-1])

    # ---- Android launcher (adaptive + monochrome + legacy PNGs) ----
    write(RES / 'drawable/ic_launcher_foreground.xml', vector(108, 108, ADAPTIVE_CAP, '#FFFFFF', RED_ON_INK.upper()))
    write(RES / 'drawable/ic_launcher_monochrome.xml', vector(108, 108, ADAPTIVE_CAP, '#FFFFFF', '#FFFFFF'))
    adaptive = '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
'''
    write(RES / 'mipmap-anydpi-v26/ic_launcher.xml', adaptive)
    write(RES / 'mipmap-anydpi-v26/ic_launcher_round.xml', adaptive)
    write(RES / 'values/ic_launcher_background.xml', f'''<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">{INK.upper()}</color>
</resources>
''')
    for density, size in {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192}.items():
        render(svg(size, FULL_CAP, bg=INK, ink=PAPER, red=RED_ON_INK, radius=0.18), RES / f'mipmap-{density}/ic_launcher.png', size)
        render(svg(size, FULL_CAP, bg=INK, ink=PAPER, red=RED_ON_INK, radius=0.5), RES / f'mipmap-{density}/ic_launcher_round.png', size)

    # ---- Splash: Android 12+ SplashScreen icon and the legacy window background ----
    # Colours come from resources, so values-night switches both to the dark palette.
    write(RES / 'drawable/splash_icon.xml', vector(288, 288, SPLASH_CAP, '@color/splash_ink', '@color/splash_accent'))
    write(RES / 'drawable/splash_mark.xml', vector(288, 288, SPLASH_CAP, '@color/splash_ink', '@color/splash_accent'))
    write(RES / 'drawable/splash.xml', '''<?xml version="1.0" encoding="utf-8"?>
<!-- Legacy launch background (before Android 12): paper colour with the mark centred. -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@color/splash_background" />
    <item
        android:width="288dp"
        android:height="288dp"
        android:drawable="@drawable/splash_mark"
        android:gravity="center" />
</layer-list>
''')
    colors = '''<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="splash_background">{bg}</color>
    <color name="splash_ink">{ink}</color>
    <color name="splash_accent">{red}</color>
</resources>
'''
    write(RES / 'values/splash_colors.xml', colors.format(bg=PAPER.upper(), ink=INK.upper(), red=RED.upper()))
    write(RES / 'values-night/splash_colors.xml', colors.format(bg=DARK_BG.upper(), ink=DARK_INK.upper(), red=DARK_RED.upper()))
    print('Brand assets written.')


if __name__ == '__main__':
    main()
