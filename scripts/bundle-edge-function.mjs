/**
 * Bundles supabase/functions/link-preview into one file for the Supabase dashboard editor
 * (Edge Functions → Deploy a new function → Via editor), for when the CLI is not available.
 *
 *   npm run edge:bundle [-- <output file>]
 *
 * The npm: import stays external; the dashboard's Deno runtime resolves it.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = resolve(process.argv[2] ?? resolve(root, 'dist-edge/link-preview/index.ts'));

const result = await build({
  bundle: true,
  entryPoints: [resolve(root, 'supabase/functions/link-preview/index.ts')],
  external: ['npm:*'],
  format: 'esm',
  legalComments: 'none',
  platform: 'neutral',
  target: 'es2022',
  write: false,
});

const header = `// Generated by scripts/bundle-edge-function.mjs from supabase/functions/link-preview.
// Paste into the Supabase dashboard editor as the function "link-preview". Do not edit here.
// Types were checked in the source (deno check); the bundle is plain JavaScript.
// @ts-nocheck
`;
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, header + result.outputFiles[0].text);
console.log(`Wrote ${output} (${readFileSync(output).length} bytes)`);
